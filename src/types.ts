// ── OM types ──

export const OBSERVATION_CUSTOM_TYPE = "hybrid-memory.observation";

export type Relevance = "low" | "medium" | "high" | "critical";
// Memory handles generated by observer/reflector makeId(): 8-char base-36
// timestamp suffix + 4-char base-36 counter. This intentionally differs from
// Pi's native 8-character hex entry IDs, which identify source entries rather
// than recallable observations/reflections.
export const MEMORY_ID_PATTERN = /^[a-z0-9]{12}$/;

export interface ObservationRecord {
  id: string;
  content: string;
  timestamp: string;
  relevance: Relevance;
  sourceEntryIds?: string[];
}

export type LegacyReflection = string;

export interface ReflectionRecord {
  id: string;
  content: string;
  supportingObservationIds: string[];
  legacy?: boolean;
}

export type MemoryReflection = LegacyReflection | ReflectionRecord;

export interface MemoryDetailsV4 {
  type: "observational-memory";
  version: 4;
  observations: ObservationRecord[];
  reflections: MemoryReflection[];
}

export interface ObservationRetirement {
  observationId: string;
  reason: "exact-duplicate";
  preservedByObservationIds: [string];
  preservedByReflectionIds: [];
}

export interface ReflectionSupersession {
  reflectionId: string;
  supersededByReflectionId: string;
  reason: "strengthened";
}

export interface MemoryLifecycleDetailsV5 {
  type: "observational-memory";
  version: 5;
  generation: {
    inputFingerprint: string;
    parentMemoryCompactionId?: string;
  };
  reflectionsAdded: ReflectionRecord[];
  observationsRetired: ObservationRetirement[];
  reflectionsSuperseded: ReflectionSupersession[];
}

export type PersistedMemoryDetails = MemoryDetailsV4 | MemoryLifecycleDetailsV5;

export interface SourceProgress {
  sourceEntryId: string;
  nextOffset: number;
  totalLength: number;
}

export interface ObservationEntryData {
  records: ObservationRecord[];
  coversFromId: string;
  coversUpToId: string;
  tokenCount: number;
  sourceProgress?: SourceProgress;
}

