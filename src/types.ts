const RELEVANCE_VALUES = new Set<Relevance>(["low", "medium", "high", "critical"]);

const isObservationRecord = (value: unknown): value is ObservationRecord => {
  if (!value || typeof value !== "object" || Array.isArray(value)) return false;
  const record = value as Record<string, unknown>;
  return typeof record.id === "string"
    && MEMORY_ID_PATTERN.test(record.id)
    && typeof record.content === "string"
    && record.content.length > 0
    && typeof record.timestamp === "string"
    && RELEVANCE_VALUES.has(record.relevance as Relevance)
    && (record.sourceEntryIds === undefined
      || (Array.isArray(record.sourceEntryIds)
        && record.sourceEntryIds.every(id => typeof id === "string" && id.length > 0)));
};

const isMemoryReflection = (value: unknown): value is MemoryReflection => {
  if (typeof value === "string") return value.length > 0;
  if (!value || typeof value !== "object" || Array.isArray(value)) return false;
  const reflection = value as Record<string, unknown>;
  return typeof reflection.id === "string"
    && MEMORY_ID_PATTERN.test(reflection.id)
    && typeof reflection.content === "string"
    && reflection.content.length > 0
    && Array.isArray(reflection.supportingObservationIds)
    && reflection.supportingObservationIds.every(id => typeof id === "string" && id.length > 0)
    && (reflection.legacy === undefined || typeof reflection.legacy === "boolean");
};

const isReflectionRecord = (value: unknown): value is ReflectionRecord =>
  typeof value !== "string" && isMemoryReflection(value);

const isReflectionSupersession = (value: unknown): value is ReflectionSupersession => {
  if (!value || typeof value !== "object" || Array.isArray(value)) return false;
  const supersession = value as Record<string, unknown>;
  return typeof supersession.reflectionId === "string"
    && MEMORY_ID_PATTERN.test(supersession.reflectionId)
    && typeof supersession.supersededByReflectionId === "string"
    && MEMORY_ID_PATTERN.test(supersession.supersededByReflectionId)
    && supersession.reason === "strengthened";
};

const isObservationRetirement = (value: unknown): value is ObservationRetirement => {
  if (!value || typeof value !== "object" || Array.isArray(value)) return false;
  const retirement = value as Record<string, unknown>;
  return typeof retirement.observationId === "string"
    && MEMORY_ID_PATTERN.test(retirement.observationId)
    && retirement.reason === "exact-duplicate"
    && Array.isArray(retirement.preservedByObservationIds)
    && retirement.preservedByObservationIds.length === 1
    && typeof retirement.preservedByObservationIds[0] === "string"
    && MEMORY_ID_PATTERN.test(retirement.preservedByObservationIds[0])
    && Array.isArray(retirement.preservedByReflectionIds)
    && retirement.preservedByReflectionIds.length === 0;
};

export const claimsMemoryDetailsVersion = (value: unknown, version: number): boolean => {
  if (!value || typeof value !== "object" || Array.isArray(value)) return false;
  const details = value as Record<string, unknown>;
  return details.type === "observational-memory" && details.version === version;
};

/** Read and isolate one known persisted memory-details record. */
export const readMemoryDetails = (value: unknown): PersistedMemoryDetails | undefined => {
  if (!value || typeof value !== "object" || Array.isArray(value)) return undefined;
  const details = value as Record<string, unknown>;
  if (details.type !== "observational-memory") return undefined;

  if (details.version === 3 || details.version === 4) {
    if (!Array.isArray(details.observations) || !details.observations.every(isObservationRecord)) {
      return undefined;
    }
    if (!Array.isArray(details.reflections) || !details.reflections.every(isMemoryReflection)) {
      return undefined;
    }
    return {
      type: "observational-memory",
      version: 4,
      observations: structuredClone(details.observations),
      reflections: structuredClone(details.reflections),
    };
  }

  if (details.version !== 5) return undefined;
  const generation = details.generation;
  if (!generation || typeof generation !== "object" || Array.isArray(generation)) return undefined;
  const generationRecord = generation as Record<string, unknown>;
  if (
    typeof generationRecord.inputFingerprint !== "string"
    || generationRecord.inputFingerprint.length === 0
    || (generationRecord.parentMemoryCompactionId !== undefined
      && (typeof generationRecord.parentMemoryCompactionId !== "string"
        || generationRecord.parentMemoryCompactionId.length === 0))
    || !Array.isArray(details.reflectionsAdded)
    || !details.reflectionsAdded.every(isReflectionRecord)
    || !Array.isArray(details.observationsRetired)
    || !details.observationsRetired.every(isObservationRetirement)
    || !Array.isArray(details.reflectionsSuperseded)
    || !details.reflectionsSuperseded.every(isReflectionSupersession)
  ) {
    return undefined;
  }
  return {
    type: "observational-memory",
    version: 5,
    generation: {
      inputFingerprint: generationRecord.inputFingerprint,
      ...(generationRecord.parentMemoryCompactionId
        ? { parentMemoryCompactionId: generationRecord.parentMemoryCompactionId as string }
        : {}),
    },
    reflectionsAdded: structuredClone(details.reflectionsAdded),
    observationsRetired: structuredClone(details.observationsRetired),
    reflectionsSuperseded: structuredClone(details.reflectionsSuperseded),
  };
};

